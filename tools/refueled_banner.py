#!/usr/bin/env python3
"""Generate the "ReFueled" lettering for the main-menu logo banner.

Writes game/230/MM_MenuLogo_Banner.inc: texel INDICES only (our own pixels)
plus one 32-bit hash of the six banner CLUTs. No colours, no original texels
are stored in the repository. At run time the game checks the hash against the
CLUTs of the disc it loaded and only then overwrites the banner texels.

The banner (main-menu model id 0x6B) is six texture strips, each 64x24 texels,
4 bit, each with its own CLUT; strip k holds the k-th segment of the text, left
to right, so the six strips form a 384x24 band. The script reads the six
(tpage, CLUT) pairs and the 16 CLUT colours from the disc (BIGFILE entry 215 =
main-menu VRM, entry 216 = main-menu LEV), renders the text, and quantises each
strip to the nearest colour of THAT strip's CLUT. No dithering.

The lettering is drawn straight into the 384x24 band: texels count as square
and are the same size along the whole band (on screen the ribbon curvature
cancels the uneven model lengths). It is drawn 8x supersampled, with a one
texel dark outline and a drop shadow one texel right and one row down, then
box-filtered down to the band.

Font: Alfa Slab One, SIL Open Font License 1.1 (tools/fonts/AlfaSlabOne-OFL.txt).
The font file is NOT in the repository. Download:
  https://raw.githubusercontent.com/google/fonts/main/ofl/alfaslabone/AlfaSlabOne-Regular.ttf
  SHA-256 28664afa698a3393bd5a29eec750230a0645c5301d62200e5f2d3a027fb2299d
The script refuses any other file.

  python -I tools/refueled_banner.py --game ctr-u.bin --font AlfaSlabOne-Regular.ttf
         [--out game/230/MM_MenuLogo_Banner.inc] [--preview band.png]
         [--text ReFueled] [--cap 18] [--stretch 2.2] [--tracking 3] [--fill 0.92]
  python -I tools/refueled_banner.py --selftest
"""

import argparse
import hashlib
import os
import struct
import sys

FONT_SHA256 = "28664afa698a3393bd5a29eec750230a0645c5301d62200e5f2d3a027fb2299d"
STRIPS = 6
STRIP_W = 64
STRIP_H = 24
BAND_W = STRIPS * STRIP_W
BI_MAINMENUFILE = 18 * 8 + 7 * 8 + 5 * 3  # BIGFILE entry of the main-menu VRM; LEV is +1
BANNER_MODEL = 0x6B

# Target colours (RGB888) before quantisation. Red is the CLUT index 0 colour
# of every banner strip; the others only steer the nearest-colour choice.
COL_RED = (168, 0, 0)
COL_WHITE = (248, 248, 248)
COL_OUTLINE = (0, 0, 8)
COL_SHADOW = (96, 0, 0)

DEFAULT_OUT = os.path.join("game", "230", "MM_MenuLogo_Banner.inc")


class BannerError(Exception):
    pass


# ---------------------------------------------------------------- pure helpers

def fnv1a32(data):
    h = 0x811C9DC5
    for b in data:
        h ^= b
        h = (h * 0x01000193) & 0xFFFFFFFF
    return h


def clut_hash(cluts):
    """FNV-1a 32 over the CLUTs (16 halfwords each, little-endian), strip order."""
    raw = b"".join(struct.pack("<16H", *c) for c in cluts)
    return fnv1a32(raw)


def rgb555(c):
    r, g, b = c & 31, (c >> 5) & 31, (c >> 10) & 31
    return ((r << 3) | (r >> 2), (g << 3) | (g >> 2), (b << 3) | (b >> 2))


def nearest_index(rgb, palette):
    """Index of the nearest usable colour (raw 0x0000 = transparent is never used).
    Ties go to the lowest index."""
    best, best_d = -1, None
    for i, c in enumerate(palette):
        if c == 0:
            continue
        p = rgb555(c)
        d = (p[0] - rgb[0]) ** 2 + (p[1] - rgb[1]) ** 2 + (p[2] - rgb[2]) ** 2
        if best_d is None or d < best_d:
            best, best_d = i, d
    if best < 0:
        raise BannerError("CLUT has no usable colour")
    return best


def pack_strip(rows):
    """rows: 24 lists of 64 texel indices -> 24*16 halfwords, first texel in bits 0-3."""
    out = []
    for row in rows:
        if len(row) != STRIP_W:
            raise BannerError("strip row is not 64 texels")
        for x in range(0, STRIP_W, 4):
            v = 0
            for k in range(4):
                t = row[x + k]
                if not 0 <= t <= 15:
                    raise BannerError("texel index out of range")
                v |= t << (4 * k)
            out.append(v)
    return out


def format_inc(text, cluts_hash, packed):
    lines = [
        "/* Generated by tools/refueled_banner.py - do not edit.",
        " * Text: \"%s\"" % text,
        " * Font: Alfa Slab One, SIL Open Font License 1.1 (license: tools/fonts/AlfaSlabOne-OFL.txt).",
        " * Contents: texel indices only (our own pixels); the colours are the game's own CLUTs.",
        " * s_menuLogoClutHash: FNV-1a 32 over the 6 banner CLUTs (16 halfwords each,",
        " *   little-endian bytes, strip order). Layout: per strip row-major, 16 halfwords",
        " *   per row, 4 texels per halfword, first texel in bits 0-3. */",
        "",
        "static const u32 s_menuLogoClutHash = 0x%08Xu;" % cluts_hash,
        "",
        "static const u16 s_menuLogoRefueled[%d][%d * 16] = {" % (STRIPS, STRIP_H),
    ]
    for s, hw in enumerate(packed):
        lines.append("    { /* strip %d */" % (s + 1))
        for r in range(STRIP_H):
            lines.append("        " + ",".join("0x%04X" % v for v in hw[r * 16:(r + 1) * 16]) + ",")
        lines.append("    },")
    lines.append("};")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- disc reading

class Disc:
    """BIGFILE.BIG, either raw (.big) or inside a MODE2/2352 disc image (.bin)."""

    def __init__(self, path):
        self.f = open(path, "rb")
        self.raw = path.lower().endswith(".big")
        if self.raw:
            self.base = 0
        else:
            self.base = self._find_bigfile()
        hdr = self._read(0, 8)
        _cdpos, nent = struct.unpack("<ii", hdr)
        if not 0 < nent < 100000:
            raise BannerError("BIGFILE header looks wrong")
        self.ents = struct.unpack("<%di" % (nent * 2), self._read(0, 8 + nent * 8)[8:])

    def _user(self, lba):
        self.f.seek(lba * 2352)
        s = self.f.read(2352)
        return s[24:24 + 2048]

    def _find_bigfile(self):
        pvd = self._user(16)
        if pvd[1:6] != b"CD001":
            raise BannerError("not a MODE2/2352 disc image")

        def rec(b, o):
            return b[o], struct.unpack_from("<I", b, o + 2)[0], struct.unpack_from("<I", b, o + 10)[0], b[o + 32], b[o + 33:o + 33 + b[o + 32]]

        _, lba, size, _, _ = rec(pvd, 156)
        data = b"".join(self._user(lba + i) for i in range((size + 2047) // 2048))[:size]
        o = 0
        while o < len(data):
            if data[o] == 0:
                o = (o // 2048 + 1) * 2048
                continue
            ln, l, s, _, nm = rec(data, o)
            if nm.split(b";")[0] == b"BIGFILE.BIG":
                return l
            o += ln
        raise BannerError("BIGFILE.BIG not found on the disc")

    def _read(self, sector_off, n):
        if self.raw:
            self.f.seek(sector_off * 2048)
            return self.f.read(n)
        return b"".join(self._user(self.base + sector_off + i) for i in range((n + 2047) // 2048))[:n]

    def entry(self, i):
        return self._read(self.ents[2 * i], self.ents[2 * i + 1])


def load_vram(vrm):
    """Multi-TIM (first word 0x20) or single TIM -> 1024x512 halfword VRAM bytes."""
    vram = bytearray(1024 * 512 * 2)

    def load(x, y, w, h, pix):
        for r in range(h):
            o = ((y + r) * 1024 + x) * 2
            vram[o:o + w * 2] = pix[r * w * 2:(r + 1) * w * 2]

    if struct.unpack_from("<I", vrm, 0)[0] == 0x20:
        o = 4
        size = struct.unpack_from("<I", vrm, o)[0]
        o += 4
        while size:
            x, y, w, h = struct.unpack_from("<4h", vrm, o + 0xC)
            load(x, y, w, h, vrm[o + 0x14:o + 0x14 + w * h * 2])
            o += size & ~3
            size = struct.unpack_from("<I", vrm, o)[0]
            o += 4
    else:
        x, y, w, h = struct.unpack_from("<4h", vrm, 0xC)
        load(x, y, w, h, vrm[0x14:])
    return bytes(vram)


def _banner_model(lev):
    """(LEV body, banner model header offset); the LEV starts with the size of its body."""
    mapoff = struct.unpack_from("<i", lev, 0)[0]
    body = lev[4:4 + mapoff]
    u32 = lambda o: struct.unpack_from("<I", body, o)[0]
    s16 = lambda o: struct.unpack_from("<h", body, o)[0]
    ho = None
    for i in range(u32(0x14)):
        p = u32(u32(0x18) + 4 * i)
        if s16(p + 0x10) == BANNER_MODEL:
            ho = u32(p + 0x14)
    if ho is None:
        raise BannerError("banner model 0x6B not found")
    return body, ho


def banner_pairs(lev):
    """(tpage, clut, u0, v0) per strip from the banner model, plus the shape check."""
    body, ho = _banner_model(lev)
    u32 = lambda o: struct.unpack_from("<I", body, o)[0]
    cl, tl = u32(ho + 0x20), u32(ho + 0x28)
    used = set()
    o = cl + 4
    while u32(o) != 0xFFFFFFFF:
        c = u32(o)
        if (c >> 16) != 0:
            used.add(c & 0x1FF)
        o += 4
    used.discard(0)  # index 0 = untextured command
    if used != set(range(1, 8 * STRIPS + 1)):
        raise BannerError("banner uses texture indices %s, expected 1..48" % sorted(used))
    pairs = []
    for k in range(STRIPS):
        seen = set()
        us, vs = [], []
        for ti in range(8 * k + 1, 8 * k + 9):
            lp = u32(tl + 4 * (ti - 1))
            u0, v0, clut, u1, v1, tp, u2, v2, u3, v3 = struct.unpack_from("<BBHBBHBBBB", body, lp)
            seen.add((tp, clut))
            us += [u0, u1, u2, u3]
            vs += [v0, v1, v2, v3]
        if len(seen) != 1:
            raise BannerError("strip %d mixes tpage/CLUT pairs" % (k + 1))
        tp, clut = seen.pop()
        if (tp >> 7) & 3 != 0:
            raise BannerError("strip %d is not 4 bit" % (k + 1))
        if max(us) - min(us) + 1 != STRIP_W or max(vs) - min(vs) + 1 != STRIP_H:
            raise BannerError("strip %d is %dx%d, expected 64x24" % (k + 1, max(us) - min(us) + 1, max(vs) - min(vs) + 1))
        pairs.append((tp, clut, min(us), min(vs)))
    return pairs


def read_banner(game_path):
    d = Disc(game_path)
    vram = load_vram(d.entry(BI_MAINMENUFILE))
    pairs = banner_pairs(d.entry(BI_MAINMENUFILE + 1))
    cluts = []
    for _tp, clut, _u, _v in pairs:
        cx, cy = (clut & 0x3F) * 16, (clut >> 6) & 0x1FF
        cluts.append(list(struct.unpack_from("<16H", vram, (cy * 1024 + cx) * 2)))
    return pairs, cluts


# ---------------------------------------------------------------- rendering

SS = 8  # supersampling factor of the drawing


BAND_ROW_BASE = 21  # baseline row for cap 18: cap letters span rows 3..20


def place_on_band(mask, baseline, base_row=BAND_ROW_BASE):
    """mask: L image (supersampled, any size) with the glyph run; baseline: y of
    the baseline in that image. Returns an L image of the full band at SS x,
    ink centred on column 192 and the baseline at the given band row."""
    from PIL import Image

    box = mask.getbbox()
    out = Image.new("L", (BAND_W * SS, STRIP_H * SS), 0)
    if box is None:
        return out
    cx = (box[0] + box[2]) // 2
    out.paste(mask, (BAND_W * SS // 2 - cx, int(round(base_row * SS)) - baseline))
    return out


def draw_run(text, font_path, cap, stretch, tracking):
    """Glyph run as an L mask at SS x, texels square. Returns (mask, baseline)."""
    from PIL import Image, ImageDraw, ImageFont

    target = cap * SS
    size = 20
    while True:
        f = ImageFont.truetype(font_path, size)
        b = f.getbbox("R", anchor="ls")
        if -b[1] >= target or size > 2000:
            break
        size += 1
    asc = -b[1]
    base = int(asc * 1.4)
    # natural width; tracking is given in texels of the final band
    track_nat = tracking * SS / stretch
    x = 4.0
    pos = []
    for ch in text:
        pos.append(x)
        x += f.getlength(ch) + track_nat
    w = int(x) + 8
    nat = Image.new("L", (w, int(asc * 2.0)), 0)
    d = ImageDraw.Draw(nat)
    for ch, px in zip(text, pos):
        d.text((px, base), ch, font=f, fill=255, anchor="ls")
    wide = nat.resize((max(1, int(round(w * stretch))), nat.height), Image.LANCZOS)
    return wide, base


def render_band(text, font_path, cap, stretch, tracking, fill):
    """Return (RGB image 384x24, stretch used). If the word would exceed `fill`
    of the band width, the stretch is reduced until it fits."""
    from PIL import Image, ImageChops, ImageFilter

    st = stretch
    for _ in range(40):
        wide, base = draw_run(text, font_path, cap, st, tracking)
        box = wide.getbbox()
        if box[2] - box[0] <= fill * BAND_W * SS or st < 0.3:
            break
        st *= 0.97
    lay = place_on_band(wide, base, (STRIP_H + cap) // 2)
    out = lay.filter(ImageFilter.MaxFilter(2 * SS + 1))   # 1 texel ring, 8-neighbourhood
    shadow = ImageChops.offset(out, SS, SS)               # +1 texel right, +1 row down
    size = lay.size
    img = Image.new("RGB", size, COL_RED)
    img.paste(Image.new("RGB", size, COL_SHADOW), (0, 0), shadow)
    img.paste(Image.new("RGB", size, COL_OUTLINE), (0, 0), out)
    img.paste(Image.new("RGB", size, COL_WHITE), (0, 0), lay)
    return img.resize((BAND_W, STRIP_H), Image.BOX), st


def quantise(band, cluts):
    """band: PIL RGB 384x24 -> per strip list of 24 rows of 64 indices."""
    px = band.load()
    strips = []
    for s in range(STRIPS):
        cache = {}
        rows = []
        for y in range(STRIP_H):
            r = []
            for x in range(STRIP_W):
                rgb = px[s * STRIP_W + x, y]
                if rgb not in cache:
                    cache[rgb] = nearest_index(rgb, cluts[s])
                r.append(cache[rgb])
            rows.append(r)
        strips.append(rows)
    return strips


def build_indices(cluts, text, font_path, cap=18, stretch=2.2, tracking=3, fill=0.92):
    band, asp = render_band(text, font_path, cap, stretch, tracking, fill)
    return quantise(band, cluts), asp


def write_preview(path, strips, cluts):
    from PIL import Image

    rgb = Image.new("RGB", (BAND_W, STRIP_H))
    grey = Image.new("RGB", (BAND_W, STRIP_H))
    for s in range(STRIPS):
        for y in range(STRIP_H):
            for x in range(STRIP_W):
                i = strips[s][y][x]
                rgb.putpixel((s * STRIP_W + x, y), rgb555(cluts[s][i]))
                grey.putpixel((s * STRIP_W + x, y), (i * 17,) * 3)
    sheet = Image.new("RGB", (BAND_W * 4, STRIP_H * 8 + 8), (40, 40, 40))
    sheet.paste(rgb.resize((BAND_W * 4, STRIP_H * 4), Image.NEAREST), (0, 0))
    sheet.paste(grey.resize((BAND_W * 4, STRIP_H * 4), Image.NEAREST), (0, STRIP_H * 4 + 8))
    sheet.save(path)


# ---------------------------------------------------------------- self test

def selftest():
    fails = []

    def check(name, ok):
        print("%s %s" % ("ok  " if ok else "FAIL", name))
        if not ok:
            fails.append(name)

    check("FNV-1a 32 known vector ('a' = 0xE40C292C)", fnv1a32(b"a") == 0xE40C292C)
    check("FNV-1a 32 empty = offset basis", fnv1a32(b"") == 0x811C9DC5)
    row = [1, 2, 3, 4] + [0] * 60
    p = pack_strip([row] + [[0] * 64] * 23)
    check("pack: first texel in bits 0-3", p[0] == 0x4321 and len(p) == 24 * 16)
    check("pack: 15 in top nibble", pack_strip([[0, 0, 0, 15] + [0] * 60] + [[0] * 64] * 23)[0] == 0xF000)
    pal = [0x0000, 0x001F, 0x7C00, 0x03E0] + [0x7FFF] * 12
    check("nearest: red picks idx 1, never transparent idx 0", nearest_index((250, 0, 0), pal) == 1)
    check("nearest: black target avoids transparent idx 0", nearest_index((0, 0, 0), pal) != 0)
    check("nearest: tie goes to the lowest index", nearest_index((248, 248, 248), pal) == 4)
    h1 = clut_hash([list(range(16))] * 6)
    check("clut hash is stable and order sensitive", h1 == clut_hash([list(range(16))] * 6) and h1 != clut_hash([list(range(1, 17))] + [list(range(16))] * 5))
    a = format_inc("T", 0x12345678, [[0] * 384] * 6)
    check("inc output deterministic and carries the hash", a == format_inc("T", 0x12345678, [[0] * 384] * 6) and "0x12345678u" in a)
    check("inc output holds only indices (all-zero input gives 6*384 zero words)", a.count("0x0000") == 6 * 384)
    from PIL import Image
    syn = Image.new("L", (900, 200), 0)
    syn.paste(255, (100, 50, 400, 150))
    syn.paste(255, (500, 60, 540, 150))
    placed = place_on_band(syn, 150)
    box = placed.getbbox()
    centre = (box[0] + box[2]) / 2.0 / SS
    check("layout: ink centred on column 192 (+-1 texel)", abs(centre - 192) <= 1.0)
    check("layout: baseline lands on the band baseline row", abs((box[3] / float(SS)) - BAND_ROW_BASE) <= 1.0)
    if fails:
        print("selftest FAILED: %d" % len(fails))
        return 1
    print("selftest passed")
    return 0


# ---------------------------------------------------------------- main

def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--game", help="ctr-u.bin (MODE2/2352 image) or BIGFILE.BIG")
    ap.add_argument("--font", help="AlfaSlabOne-Regular.ttf")
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    ap.add_argument("--out", default=os.path.join(root, DEFAULT_OUT))
    ap.add_argument("--preview", help="PNG with the band in the game colours (x4) and as grey indices")
    ap.add_argument("--text", default="ReFueled")
    ap.add_argument("--cap", type=int, default=18, help="cap height in texel rows")
    ap.add_argument("--stretch", type=float, default=2.2, help="horizontal scale of the glyphs against their natural shape")
    ap.add_argument("--tracking", type=float, default=3.0, help="extra texels between letters")
    ap.add_argument("--fill", type=float, default=0.92, help="largest share of the 384 columns the word may use")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args(argv)
    if a.selftest:
        return selftest()
    if not a.game or not a.font:
        ap.error("--game and --font are required")
    with open(a.font, "rb") as fh:
        if hashlib.sha256(fh.read()).hexdigest() != FONT_SHA256:
            raise BannerError("font file is not Alfa Slab One Regular (SHA-256 mismatch), see the docstring")
    pairs, cluts = read_banner(a.game)
    strips, asp = build_indices(cluts, a.text, a.font, a.cap, a.stretch, a.tracking, a.fill)
    packed = [pack_strip(s) for s in strips]
    h = clut_hash(cluts)
    with open(a.out, "w", newline="\n") as fh:
        fh.write(format_inc(a.text, h, packed))
    if a.preview:
        write_preview(a.preview, strips, cluts)
    print("wrote %s, CLUT hash 0x%08X, stretch %.2f" % (a.out, h, asp))
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except BannerError as e:
        print("error: %s" % e, file=sys.stderr)
        sys.exit(2)
